// Лист признаков на русском: ключевые слова, по которым из текста извлекаются черты.
// Его можно свободно дополнять: прилагательные записываются в мужском роде единственного
// числа («голубой», «синий», «вьющийся»), а формы рода, числа и падежа и краткие формы
// («высок», «умна», «длинны») порождает forms().
//
// Как это устроено. Слова сравниваются без ударений и диакритики: «ё» читается как «е»,
// а «й» — как «и». Поэтому forms() получает и возвращает слова уже в таком виде.
// В русском прилагательное обычно стоит перед существительным («голубые глаза»); после него
// оно засчитывается, только если за существительным сразу идёт связка («глаза были голубые»,
// «глаза у неё голубые») или само прилагательное в именительном падеже («глаза голубые,
// волосы светлые»). Так в «рыжие волосы и зелёные глаза» «зелёные» не приписывается волосам.

const strip = (s) => String(s).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();

// Прилагательные, у которых не порождаются краткие формы: их краткая форма совпадает с другим
// словом («нем» — «о нём», «хром», «пожил») или её нет вовсе.
const NO_SHORT = new Set(['немой', 'хромой', 'пожилой', 'полный', 'большой', 'маленький', 'небольшой', 'средний'].map(strip));
// Формы, которые совпадают с частыми существительными («длина волос», «добра и зла»).
const EXCLUDED = new Set(['длина', 'длины', 'длин', 'добра', 'зла'].map(strip));

const VOWEL = /[аеиоуыэюя]$/;

/** Краткая форма мужского рода с беглой гласной: «тёмен», «короток», «спокоен», «светел». */
function shortMasculine(stem) {
  const last = stem.slice(-1);
  const pre = stem.slice(0, -1);
  if (last === 'н') {
    if (stem.endsWith('нн')) return [pre + 'ен', pre];                     // длинен; уверен
    if (/[аеоуыэюя]и$/.test(pre)) return [pre.slice(0, -1) + 'ен'];        // спокойный → спокоен
    if (pre.endsWith('ь')) return [pre.slice(0, -1) + 'ен'];               // сильный → силён
    if (!VOWEL.test(pre)) return [pre + 'ен'];                              // тёмный → тёмен
    return [stem];                                                          // зелёный → зелен
  }
  if (last === 'к' && !VOWEL.test(pre)) {
    if (pre.endsWith('ь')) return [pre.slice(0, -1) + 'ек'];               // горький → горек
    if (/[жшчщ]$/.test(pre)) return [pre + 'ек'];                          // тяжкий → тяжек
    return [pre + 'ок'];                                                    // короткий → короток
  }
  if ((last === 'л' || last === 'р') && !VOWEL.test(pre)) return [stem, pre + 'е' + last]; // светел, хитёр
  return [stem];                                                            // высок, молод
}

/**
 * Формы прилагательного (слово уже без диакритики: «голубои», «синии», «вьющиися»).
 * Возвращает { nominative, all } или null, если это не полное прилагательное.
 * nominative: именительный падеж и краткие формы — то, что может стоять после существительного.
 */
function declension(input) {
  let word = strip(input);
  let tail = '';
  if (/[ыио]ися$/.test(word)) { tail = 'ся'; word = word.slice(0, -2); }    // вьющийся, сросшийся
  const m = /^(.+?)(ыи|ии|ои)$/.exec(word);
  if (!m || m[1].length < 2) return null;
  const stem = m[1];
  const stressed = m[2] === 'ои';
  const velar = /[гкх]$/.test(stem);
  const hush = /[жшчщ]$/.test(stem);
  const soft = m[2] === 'ии' && !velar && !hush;
  const y = velar || hush || soft ? 'и' : 'ы';
  const o = soft || (hush && !stressed) ? 'е' : 'о';
  const a = soft ? 'я' : 'а';
  const u = soft ? 'ю' : 'у';
  const nominative = [
    stressed ? stem + 'ои' : stem + y + 'и',  // голубой, синий, высокий
    stem + a + 'я',                           // -ая, -яя
    stem + o + 'е',                           // -ое, -ее
    stem + y + 'е',                           // -ые, -ие
  ];
  const oblique = [
    stem + o + 'го', stem + o + 'му', stem + o + 'м',   // -ого, -ому, -ом
    stem + y + 'м', stem + y + 'х', stem + y + 'ми',    // -ым, -ых, -ыми
    stem + u + 'ю', stem + o + 'и',                     // -ую, -ой
  ];
  // Краткие формы (кроме среднего рода: «тихо», «честно» — это наречия).
  const short = [];
  if (!tail && !soft && !NO_SHORT.has(word) && !/(ск|цк|щ|вш)$/.test(stem)) {
    const bases = stem.endsWith('нн') ? [stem, stem.slice(0, -1)] : [stem];
    short.push(...shortMasculine(stem));
    for (const b of bases) short.push(b + 'а', b + (velar || hush ? 'и' : 'ы'));
  }
  const finish = (list) => [...new Set(list.map((f) => f + tail))].filter((f) => f === word + tail || !EXCLUDED.has(f));
  const nom = finish([...nominative, ...short]);
  return { nominative: nom, all: finish([...nominative, ...short, ...oblique]) };
}

